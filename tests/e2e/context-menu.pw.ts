import { expect, test, type Locator, type Page } from '@playwright/test'

const frame=(page:Page)=>page.frameLocator('iframe[title="CoBest visual builder canvas"]')
const palette=(page:Page,name:string)=>page.locator('.vb-palette-item',{hasText:name}).first()
const drag=async(page:Page,name:string,dest:Locator)=>{
  await expect(palette(page,name)).toBeVisible()
  await palette(page,name).dragTo(dest,{force:true})
}

test('right-click shows real element tools, not only duplicate/delete',async({page})=>{
  await page.setViewportSize({width:1440,height:900})
  await page.goto('/e2e.html')
  const heading=frame(page).locator('[data-builder-node="hero-title-home"]')
  await heading.click({button:'right'})
  const menu=page.getByRole('menu',{name:/Element actions for Heading/})
  await expect(menu).toBeVisible()
  const bounds=await menu.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x+bounds!.width).toBeLessThanOrEqual(1440)
  await expect(menu.getByRole('menuitem',{name:'Edit element settings'})).toBeVisible()
  await expect(menu.getByRole('menuitem',{name:'Edit style'})).toBeVisible()
  await expect(menu.getByRole('menuitem',{name:/Select parent/})).toBeVisible()
  await expect(menu.getByRole('menuitem',{name:/Copy element/})).toBeVisible()
  await menu.getByRole('menuitem',{name:'Edit element settings'}).click()
  await expect(page.getByRole('button',{name:'Settings',exact:true})).toHaveClass(/active/)
  await expect(page.locator('.vb-right-content input').first()).toHaveValue('Heading')
  await heading.click({button:'right'})
  await page.getByRole('menuitem',{name:/Select parent/}).click()
  await expect(frame(page).locator('.builder-selected')).toHaveCount(1)
  await expect(frame(page).locator('[data-builder-node="hero-title-home"]')).not.toHaveClass(/builder-selected/)
})

test('right-click an image opens upload, library, image URL and alt text settings',async({page})=>{
  await page.goto('/e2e.html')
  await page.getByRole('button',{name:'Pages',exact:true}).click()
  await page.getByRole('button',{name:'Add page'}).click()
  await page.getByPlaceholder('Page name').fill('Image Test')
  await page.getByRole('button',{name:'Create',exact:true}).click()
  await page.getByRole('button',{name:'Add',exact:true}).click()
  const canvas=frame(page)
  await drag(page,'Section',canvas.locator('[data-builder-name="Page"]'))
  await drag(page,'Container',canvas.locator('[data-builder-type="section"]').first())
  await drag(page,'Image',canvas.locator('[data-builder-type="container"]').first())
  const image=canvas.locator('[data-builder-type="image"]').first()
  await image.click({button:'right'})
  const menu=page.getByRole('menu')
  await expect(menu).toBeVisible()
  await menu.getByRole('menuitem',{name:'Replace image / Settings'}).click()
  await expect(page.getByRole('region',{name:'Image settings'})).toBeVisible()
  const testUrl='https://example.com/cobest-image-test.png'
  await page.getByRole('textbox',{name:'Image URL'}).fill(testUrl)
  await expect(image).toHaveAttribute('src',testUrl)
  const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl7jZ0AAAAASUVORK5CYII=','base64')
  await page.getByLabel('Upload replacement image').setInputFiles({
    name:'replacement.png',mimeType:'image/png',buffer:png,
  })
  await expect.poll(()=>image.getAttribute('src')).toMatch(/^data:image\/png;base64,/)
  await expect(page.getByRole('button',{name:'Use image replacement.png'})).toBeVisible()
  await page.getByRole('textbox',{name:'Image alt text'}).fill('Our team collaborating')
  await expect(image).toHaveAttribute('alt','Our team collaborating')
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.vb-save-status')).toHaveText('Saved')
  await page.reload()
  await expect(canvas.locator('[data-builder-type="image"]').first()).toHaveAttribute('alt','Our team collaborating')
  await expect.poll(()=>canvas.locator('[data-builder-type="image"]').first().getAttribute('src')).toMatch(/^data:image\/png;base64,/)
})
