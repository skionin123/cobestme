import {expect,test} from '@playwright/test'

test('beginner guide connects actual theme, section and content tools without blocking editing',async({page})=>{
  await page.goto('/e2e.html')
  await expect(page.getByRole('note')).toContainText('First time here?')
  await page.getByRole('button',{name:'Show my steps'}).click()
  const guide=page.getByRole('region',{name:'Website editor getting started guide'})
  await expect(guide).toBeVisible()
  await expect(guide).toContainText('Your first website, step by step.')
  await expect(guide).toContainText('Draft changes are not automatically published.')
  await expect(guide.locator('.vb-guide-step')).toHaveCount(6)
  await guide.getByRole('button',{name:/Browse themes/}).click()
  await expect(guide).toHaveCount(0)
  await expect(page.getByText('Start with a ready-made design.')).toBeVisible()
  await page.getByRole('button',{name:'Website building guide'}).click()
  await guide.getByRole('button',{name:/Add section/}).click()
  await expect(page.getByRole('dialog',{name:'Search or add website elements'})).toBeVisible()
  await page.getByRole('textbox',{name:'Search website tools'}).fill('Store announcement')
  await page.getByRole('button',{name:'Find Store announcement section'}).click()
  await expect(page.frameLocator('iframe[title="CoBest visual builder canvas"]').getByText(/announcement/i).first()).toBeVisible()
  await page.getByRole('button',{name:'Website building guide'}).click()
  await guide.getByRole('button',{name:/Select an element|Edit selected/}).click()
  await expect(page.locator('.vb-right')).toBeVisible()
  await expect(page.getByRole('navigation',{name:'Selected element hierarchy'})).toBeVisible()
})

test.describe('guide stays usable on phones',()=>{
  test.use({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  test('guide can open and switch to mobile preview',async({page})=>{
    await page.goto('/e2e.html')
    await page.getByRole('button',{name:'Website building guide'}).click()
    const guide=page.getByRole('region',{name:'Website editor getting started guide'})
    await expect(guide).toBeVisible()
    await expect(guide.getByRole('button',{name:/See mobile view/})).toBeVisible()
    await guide.getByRole('button',{name:/See mobile view/}).click()
    await expect(guide).toHaveCount(0)
    await expect(page.locator('.vb-stage-crumb')).toContainText('Mobile portrait 478')
    await expect(page.getByRole('navigation',{name:'Phone website editing tools'})).toBeVisible()
    await page.getByRole('button',{name:'Website building guide'}).click()
    await expect(guide).toBeVisible()
    await guide.getByRole('button',{name:'Close website guide'}).click()
    await expect(guide).toHaveCount(0)
  })
})
