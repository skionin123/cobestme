import {test,expect} from '@playwright/test'

// Shopify-inspired merchant flow: sections are structured and reversible.
test('add a section at the chosen position, move it, undo and open version history',async({page})=>{
  await page.goto('/e2e.html')
  await page.getByRole('button',{name:'Navigator',exact:true}).click()
  await page.getByRole('button',{name:'Add section after Hero'}).click()
  await page.getByRole('button',{name:'Insert Features grid after Hero'}).click()
  const features=page.getByRole('button',{name:'Select Features layer'})
  const hero=page.getByRole('button',{name:'Select Hero layer'})
  await expect(features).toBeVisible()
  await expect(page.getByRole('button',{name:'Move section Features up'})).toBeEnabled()
  await page.getByRole('button',{name:'Move section Features up'}).click()
  expect(await features.evaluate(el=>Boolean(el.compareDocumentPosition(document.querySelector('[aria-label="Select Hero layer"]'))&Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true)
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  expect(await hero.evaluate(el=>Boolean(el.compareDocumentPosition(document.querySelector('[aria-label="Select Features layer"]'))&Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true)
  await page.getByRole('button',{name:'Redo',exact:true}).click()
  await page.getByRole('button',{name:'Version history'}).click()
  await expect(page.getByRole('dialog',{name:'Saved design versions'})).toBeVisible()
  await expect(page.getByRole('dialog',{name:'Saved design versions'}).getByText('Move element')).toBeVisible()
})

test.describe('phone section editing',()=>{
  test.use({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  test('tap section insertion and reorder without a precision drag',async({page})=>{
    await page.goto('/e2e.html')
    const tools=page.getByRole('navigation',{name:'Phone website editing tools'})
    await tools.getByRole('button',{name:'Phone Layers'}).click()
    await page.getByRole('button',{name:'Add section after Hero'}).click()
    await page.getByRole('button',{name:'Insert FAQ accordion after Hero'}).click()
    await expect(page.getByRole('button',{name:'Select FAQ layer'})).toBeVisible()
    await page.getByRole('button',{name:'Move section FAQ up'}).click()
    await tools.getByRole('button',{name:'Phone Undo'}).click()
    await tools.getByRole('button',{name:'Phone Redo'}).click()
    await tools.getByRole('button',{name:'Phone Edit content'}).click()
    await expect(page.locator('.vb-right.vb-mobile-open')).toBeVisible()
    await expect(page.getByRole('button',{name:'Settings',exact:true})).toBeVisible()
    await tools.getByRole('button',{name:'Phone Layers'}).click()
    await page.getByRole('button',{name:'Select Heading layer'}).first().click()
    await tools.getByRole('button',{name:'Phone Edit content'}).click()
    const headingText=page.locator('.vb-right.vb-mobile-open').getByRole('textbox',{name:'Text'})
    await headingText.fill('Welcome to our online store')
    await expect(page.frameLocator('iframe[title="CoBest visual builder canvas"]').locator('[data-builder-node="hero-title-home"]'))
      .toHaveText('Welcome to our online store')
    await tools.getByRole('button',{name:'Phone Save'}).click()
    await expect(page.locator('.vb-save-status')).toHaveText('Saved')
  })
})
