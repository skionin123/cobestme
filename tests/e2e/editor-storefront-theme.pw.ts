import {expect,test} from '@playwright/test'

test('desktop merchants can choose and apply an online-store theme',async({page})=>{
  await page.goto('/e2e.html')
  await page.getByRole('button',{name:'Themes',exact:true}).click()
  await expect(page.getByText('Start with a ready-made design.')).toBeVisible()
  const apply=page.getByRole('button',{name:'Use Online Store'})
  await expect(apply).toBeVisible()
  page.once('dialog',dialog=>dialog.accept())
  await apply.click()
  const preview=page.frameLocator('iframe[title="CoBest visual builder canvas"]')
  await expect(preview.getByText('Explore our collection')).toBeVisible()
  await expect(preview.getByText('Information for shoppers')).toBeVisible()
  await page.getByRole('button',{name:'Version history'}).click()
  await expect(page.getByRole('dialog',{name:'Saved design versions'})).toBeVisible()
})

test.describe('merchant editing on a phone',()=>{
  test.use({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  test('tapping a heading opens an easy content editor and can change the copy',async({page})=>{
    await page.goto('/e2e.html')
    const frame=page.frameLocator('iframe[title="CoBest visual builder canvas"]')
    await frame.locator('[data-builder-node="hero-title-home"]').click()
    const drawer=page.locator('.vb-right.vb-mobile-open')
    await expect(drawer).toBeVisible()
    const quick=drawer.getByRole('textbox',{name:'Text',exact:true})
    await quick.fill('A shop designed by me')
    await expect(frame.locator('[data-builder-node="hero-title-home"]')).toHaveText('A shop designed by me')
    await page.getByRole('navigation',{name:'Phone website editing tools'})
      .getByRole('button',{name:'Phone Save'}).click()
    await expect(page.locator('.vb-save-status')).toHaveText('Saved')
  })
  test('phone Add menu exposes a complete Online Store theme',async({page})=>{
    await page.goto('/e2e.html')
    const tools=page.getByRole('navigation',{name:'Phone website editing tools'})
    await tools.getByRole('button',{name:'Phone Add elements'}).click()
    await page.getByRole('button',{name:'Choose a website theme'}).click()
    const use=page.getByRole('button',{name:'Use Online Store'})
    await expect(use).toBeVisible()
    page.once('dialog',dialog=>dialog.accept())
    await use.click()
    await expect(page.frameLocator('iframe[title="CoBest visual builder canvas"]').getByText('Explore our collection')).toBeVisible()
  })
})
